# Render app-store/listing.md from listing.json, with a character count for every field.
# Usage: python3 docs/design-marketing/tools/listing.py   (fails when a field exceeds its limit)
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent / 'app-store'
FIELDS = [('name', 'Name', 30), ('subtitle', 'Subtitle', 30), ('promotional_text', 'Promotional text', 170),
          ('keywords', 'Keywords', 100), ('whats_new', "What's New in 1.0", 4000),
          ('description', 'Description', 4000)]
INTRO = '''<!-- Generated by docs/design-marketing/tools/listing.py from listing.json; edit the JSON. -->
# App Store listing copy for HiBoss 1.0

Proposed copy for `ai.hiboss.app`, in en-US and zh-Hans. Counts are Unicode code points, which is
how App Store Connect counts the limited fields. `ios/AppStore/metadata/` holds the copy that was
written earlier; this file does not change it. `docs/design-marketing.md` lists what differs.
'''


def main() -> None:
    listing = json.loads((HERE / 'listing.json').read_text(encoding='utf-8'))
    lines, failures = [INTRO], []
    for locale, fields in listing.items():
        lines.append(f'## {locale}\n')
        for key, label, limit in FIELDS:
            count = len(fields[key])
            if count > limit:
                failures.append(f'{locale} {key}: {count} > {limit}')
            lines.append(f'### {label} ({count} of {limit} characters)\n')
            lines.append('```text\n' + fields[key] + '\n```\n')
    (HERE / 'listing.md').write_text('\n'.join(lines), encoding='utf-8')
    if failures:
        raise SystemExit('over limit: ' + '; '.join(failures))


if __name__ == '__main__':
    main()
