// Shared intrinsic dimensions for option rows and their height estimator.
// Exports: OptionRowMetrics used by thumbnail views and OptionPanelLayout.
// Dependencies: Foundation CGFloat.

import Foundation

enum OptionRowMetrics {
    static let verticalPadding: CGFloat = 9
    static let horizontalPadding: CGFloat = 13
    static let minimumHeight: CGFloat = 35
    static let rowSpacing: CGFloat = 7
    static let mediaWidth: CGFloat = 132
    static let mediaHeight: CGFloat = 96
    static let mediaSpacing: CGFloat = 8
    static let captionSpacing: CGFloat = 4
    static let descriptionSpacing: CGFloat = 4
}
